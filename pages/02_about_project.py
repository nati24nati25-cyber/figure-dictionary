
import streamlit as st

# Настройка заголовка страницы (будет в вкладке браузера)
st.set_page_config(page_title="О проекте", page_icon="📚")

st.title("📘 О проекте: Словарь терминов фигурного катания")

st.markdown("""
Эта страница содержит описание проекта, методику сбора данных и практическую значимость словаря 
для переводоведения.
""")

with st.expander("🗂 Что за словарь и как он собирался?"):
    st.write("""
    **Тип словаря:** Терминологический, двуязычный (русско-английский), узкоспециальный.  
    **Предметная область:** Фигурное катание (термины элементов, судейства, описания программ).
    
    **Этапы сбора данных:**
    1. **Сбор корпуса:** Транскрипты соревнований ISU, интервью спортсменов, статьи спортивных СМИ.
    2. **Очистка:** Удаление дублей, нормализация регистра, фильтрация нерелевантных текстов.
    3. **Извлечение терминов:** Частотный анализ + экспертная верификация (ручная проверка списка терминов).
    4. **Разметка:** Добавление грамматических и стилистических помет, перевод эквивалентов.
    """)

with st.expander("💡 Практическая значимость для переводоведения"):
    st.write("""
    Словарь решает конкретные проблемы переводчика в спортивной сфере:
    *   **Устоявшиеся варианты перевода:** Показывает, какие английские эквиваленты реально используются в трансляциях и статьях (избегает калькирования).
    *   **Коллокации:** Демонстрирует типичные словосочетания (например, *triple toe loop* vs *a toe loop jump*), что критично для естественного звучания текста.
    *   **Пометы:** Указывает на регистр (проф., спорт.) и частоту употребления, помогая выбрать вариант под конкретный тип текста (новость, репортаж, технический протокол).
    """)

with st.expander("🛠 Используемые модули и технологии (для app.py на GitHub)"):
    st.write("""
    | Модуль | Назначение |
    | --- | --- |
    | `streamlit` | Веб-интерфейс приложения |
    | `pandas` | Хранение и обработка данных словаря |
    | `spaCy` / `nltk` | Токенизация, лемматизация, поиск коллокаций |
    | `gTTS` | Синтез речи (озвучка терминов) |
    | `sqlite3` | Локальное хранение данных (опционально) |
    """)
    st.info("Полный список зависимостей указан в файле `requirements.txt` в репозитории на GitHub.")

with st.expander("⚠️ Особенности деплоя (про Streamlit)"):
    st.write("""
    Приложение разработано на Streamlit. Для стабильной работы вне среды разработки 
    рекомендуется запуск через Docker-контейнер (файл `Dockerfile` прилагается в репозитории). 
    Это позволяет избежать проблем с зависимостями и нехваткой ресурсов на хостинге.
    """)

